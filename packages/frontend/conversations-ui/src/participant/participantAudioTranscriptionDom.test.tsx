import { act, useState } from 'react'

import type { ParticipantTranscription } from '@adatechnology/conversation-contracts'
import { afterAll, afterEach, beforeAll, describe, expect, it } from 'bun:test'

import { setupDom, type DomHarness } from '../domHarness.test-helper'
import { ParticipantAudioTranscription } from './ParticipantAudioTranscription'
import { ParticipantCopyAnnouncer, ParticipantThreadLive } from './ParticipantCopyAnnouncer'
import { DEFAULT_PARTICIPANT_AUDIO_LABELS } from './participantAudioLabels'

let harness: DomHarness
let container: HTMLElement
let setTranscription: (next: ParticipantTranscription | undefined) => void = () => undefined
let overflow = { scrollHeight: 100, clientHeight: 100 }
let prototype: Record<string, unknown> = {}
let originals: Record<string, PropertyDescriptor | undefined> = {}

const READY: ParticipantTranscription = { status: 'ready', text: 'Chego em dez minutos.', language: 'pt', generatedAt: '2026-10-01T12:01:00.000Z' }

beforeAll(async () => {
  harness = await setupDom()
  prototype = HTMLElement.prototype as unknown as Record<string, unknown>
  originals = {
    scrollHeight: Object.getOwnPropertyDescriptor(prototype, 'scrollHeight'),
    clientHeight: Object.getOwnPropertyDescriptor(prototype, 'clientHeight'),
  }
  Object.defineProperty(prototype, 'scrollHeight', { configurable: true, get: () => overflow.scrollHeight })
  Object.defineProperty(prototype, 'clientHeight', { configurable: true, get: () => overflow.clientHeight })
})

afterAll(() => {
  for (const [name, descriptor] of Object.entries(originals)) {
    if (descriptor) Object.defineProperty(prototype, name, descriptor)
    else delete prototype[name]
  }
  harness.teardown()
})

afterEach(() => {
  overflow = { scrollHeight: 100, clientHeight: 100 }
})

function Harness({ initial, attachmentId = 'att-1' }: { initial: ParticipantTranscription | undefined; attachmentId?: string }) {
  const [transcription, update] = useState(initial)
  setTranscription = update
  return (
    <ParticipantCopyAnnouncer>
      <ParticipantThreadLive notice="" />
      <ParticipantAudioTranscription attachmentId={attachmentId} transcription={transcription} labels={DEFAULT_PARTICIPANT_AUDIO_LABELS} />
    </ParticipantCopyAnnouncer>
  )
}

function mount(initial: ParticipantTranscription | undefined, attachmentId?: string): void {
  container = harness.mount(<Harness initial={initial} {...(attachmentId === undefined ? {} : { attachmentId })} />).container
}

function liveText(): string {
  return container.querySelector('[role="status"]')?.textContent ?? ''
}

function change(next: ParticipantTranscription | undefined): void {
  act(() => setTranscription(next))
}

describe('announcement through the existing live region', () => {
  it('announces "Transcription ready" once on the observed pending to ready change', () => {
    mount({ status: 'pending' })
    expect(liveText()).toBe('')
    change(READY)
    expect(liveText()).toBe('Transcription ready')
    expect(container.querySelectorAll('[aria-live]')).toHaveLength(1)
  })

  it('does not announce a transcription that is already ready at the first render', () => {
    mount(READY)
    expect(liveText()).toBe('')
  })

  it('does not announce again on a re-render that stays ready, nor for failed or empty transitions', () => {
    mount({ status: 'pending' })
    change(READY)
    act(() => undefined)
    const announced = liveText()
    change({ ...READY, text: 'Outra coisa' })
    expect(liveText()).toBe(announced)

    mount({ status: 'pending' })
    change({ status: 'failed' })
    expect(liveText()).toBe('')
  })

  it('does not announce the full text', () => {
    mount({ status: 'pending' })
    change(READY)
    expect(liveText()).not.toContain('dez minutos')
  })
})

describe('states', () => {
  it('pending shows the discreet notice only', () => {
    mount({ status: 'pending' })
    expect(container.querySelector('.cv-p-transcription--pending')?.textContent).toBe('Transcribing…')
  })

  it('ready keeps the machine notice always next to the text, notice read first', () => {
    mount(READY)
    const text = container.querySelector('.cv-p-transcription__text')
    const notice = container.querySelector('.cv-p-transcription__notice')
    expect(text?.textContent).toBe('Chego em dez minutos.')
    expect(text?.getAttribute('lang')).toBe('pt')
    expect(notice?.textContent).toBe('Transcription generated by machine')
    expect(text?.getAttribute('aria-describedby')).toBe(notice?.id ?? 'missing')
    const order = Array.from(container.querySelector('.cv-p-transcription')?.children ?? [])
    expect(order.indexOf(notice as Element)).toBeLessThan(order.indexOf(text as Element))
  })

  it('empty text shows only the empty message and the notice', () => {
    mount({ status: 'ready', text: '', generatedAt: READY.status === 'ready' ? READY.generatedAt : '' })
    expect(container.querySelector('.cv-p-transcription__empty')?.textContent).toBe('Nothing was said in the audio')
    expect(container.querySelector('.cv-p-transcription__notice')).not.toBeNull()
    expect(container.querySelector('.cv-p-transcription__text')).toBeNull()
  })

  it('too_long computes the minutes from the field and is not an alarm', () => {
    mount({ status: 'failed', reason: 'too_long', maxDurationMs: 600_000 })
    const block = container.querySelector('.cv-p-transcription--too-long')
    expect(block?.textContent).toBe('Transcription only for audios shorter than 10 minutes')
    expect(block?.getAttribute('role')).toBeNull()
    change({ status: 'failed', reason: 'too_long', maxDurationMs: 300_000 })
    expect(container.querySelector('.cv-p-transcription--too-long')?.textContent).toContain('shorter than 5 minutes')
  })

  it('plain failed, too_long without the limit, a limit without reason, disabled and absent draw nothing', () => {
    for (const transcription of [
      { status: 'failed' },
      { status: 'failed', reason: 'too_long' },
      { status: 'failed', maxDurationMs: 600_000 },
      { status: 'failed', reason: 'too_long', maxDurationMs: 30_000 },
      { status: 'disabled' },
      undefined,
    ] as (ParticipantTranscription | undefined)[]) {
      mount(transcription)
      expect(container.querySelector('.cv-p-transcription')).toBeNull()
      expect(container.textContent).not.toMatch(/error|fail/i)
    }
  })
})

describe('collapse', () => {
  const LONG: ParticipantTranscription = { status: 'ready', text: 'x '.repeat(500), generatedAt: '2026-10-01T12:01:00.000Z' }

  it('shows no button when the text fits', () => {
    mount(LONG)
    expect(container.querySelector('.cv-p-transcription__toggle')).toBeNull()
  })

  it('measures the overflow, then expands and collapses with aria-expanded', () => {
    overflow = { scrollHeight: 200, clientHeight: 100 }
    mount(LONG)
    const toggle = container.querySelector<HTMLButtonElement>('.cv-p-transcription__toggle')
    expect(toggle?.textContent).toBe('Show all')
    expect(toggle?.getAttribute('aria-expanded')).toBe('false')
    expect(container.querySelector('.cv-p-transcription__text')?.textContent).toBe(LONG.text)
    act(() => toggle?.click())
    const expanded = container.querySelector<HTMLButtonElement>('.cv-p-transcription__toggle')
    expect(expanded?.textContent).toBe('Show less')
    expect(expanded?.getAttribute('aria-expanded')).toBe('true')
    act(() => expanded?.click())
    expect(container.querySelector('.cv-p-transcription__toggle')?.getAttribute('aria-expanded')).toBe('false')
  })
})

describe('the transcribed text never leaves the paragraph', () => {
  it('is in no title, data-* attribute or tooltip', () => {
    mount(READY)
    const everything = Array.from(container.querySelectorAll('*'))
    for (const element of everything) {
      for (const attribute of Array.from(element.attributes)) {
        if (attribute.name === 'title' || attribute.name.startsWith('data-')) expect(attribute.value).not.toContain('dez minutos')
      }
    }
  })
})
