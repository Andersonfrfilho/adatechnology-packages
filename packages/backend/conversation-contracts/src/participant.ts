import { z } from 'zod'

import {
  attachmentKindSchema,
  conversationChannelSchema,
  messageDeliveryStatusSchema,
  messageDirectionSchema,
} from './vocabulary'

export const SUBJECT_TYPE_PATTERN = /^[a-z][a-z0-9_-]{0,63}$/

export const subjectRefSchema = z.object({
  subjectType: z.string().regex(SUBJECT_TYPE_PATTERN),
  subjectId: z.string().min(1).max(128),
})
export type ParticipantSubjectRef = z.infer<typeof subjectRefSchema>

export const PARTICIPANT_CONVERSATION_STATUS = Object.freeze(['open', 'closed'] as const)
export type ParticipantConversationStatus = (typeof PARTICIPANT_CONVERSATION_STATUS)[number]
export const participantConversationStatusSchema = z.enum(PARTICIPANT_CONVERSATION_STATUS)

/** Readable conversation code generated by the product (never by this package); shown, copied and searched only. */
const PARTICIPANT_PROTOCOL_PATTERN = /^[A-Za-z0-9-]+$/

/** Opaque icon name chosen by the product; this package never knows the catalog behind it. */
const PARTICIPANT_ICON_NAME_PATTERN = /^[a-z0-9-]+$/

const participantChannelsSchema = z
  .array(conversationChannelSchema)
  .max(5)
  .refine((channels) => new Set(channels).size === channels.length, { message: 'channels must not repeat' })

export const participantConversationSummarySchema = subjectRefSchema.extend({
  subjectLabel: z.string().min(1).max(200),
  protocol: z.string().min(1).max(32).regex(PARTICIPANT_PROTOCOL_PATTERN).optional(),
  lastMessageAt: z.string().datetime().nullable(),
  lastMessagePreview: z.string().max(280).optional(),
  lastMessageDirection: messageDirectionSchema.optional(),
  unreadCount: z.number().int().min(0),
  awaitingParticipant: z.boolean(),
  status: participantConversationStatusSchema,
  attributes: z.record(z.string(), z.string()).optional(),
  channels: participantChannelsSchema.optional(),
  iconName: z.string().min(1).max(32).regex(PARTICIPANT_ICON_NAME_PATTERN).optional(),
})
export type ParticipantConversationSummary = z.infer<typeof participantConversationSummarySchema>

export const participantConversationPageSchema = z.object({
  data: z.array(participantConversationSummarySchema),
  nextCursor: z.string().min(1).optional(),
})
export type ParticipantConversationPage = z.infer<typeof participantConversationPageSchema>

export const PARTICIPANT_TRANSCRIPTION_STATUS = Object.freeze(['pending', 'ready', 'failed', 'disabled'] as const)
export type ParticipantTranscriptionStatus = (typeof PARTICIPANT_TRANSCRIPTION_STATUS)[number]

/** Só o motivo que muda o que o leitor vê; os demais códigos de falha ficam no servidor. */
export const PARTICIPANT_TRANSCRIPTION_FAILURE_REASONS = Object.freeze(['too_long'] as const)

/** Em unidades UTF-16, que é o que `.max` do zod conta. */
export const PARTICIPANT_TRANSCRIPTION_TEXT_MAX_UTF16 = 40_000
export const PARTICIPANT_AUDIO_DURATION_MAX_MS = 86_400_000

/** Sem `.strict()` nem `refine`: campo fora do ramo é descartado, não recusado. */
export const participantTranscriptionSchema = z.discriminatedUnion('status', [
  z.object({ status: z.literal('pending') }),
  z.object({
    status: z.literal('ready'),
    text: z.string().max(PARTICIPANT_TRANSCRIPTION_TEXT_MAX_UTF16),
    language: z
      .string()
      .regex(/^[a-z]{2,3}$/)
      .optional(),
    engine: z.string().min(1).max(64).optional(),
    generatedAt: z.string().datetime(),
  }),
  z.object({
    status: z.literal('failed'),
    reason: z.enum(PARTICIPANT_TRANSCRIPTION_FAILURE_REASONS).optional(),
    maxDurationMs: z.number().int().positive().optional(),
  }),
  z.object({ status: z.literal('disabled') }),
])
export type ParticipantTranscription = z.infer<typeof participantTranscriptionSchema>

export const participantAttachmentSchema = z.object({
  id: z.string().min(1),
  kind: attachmentKindSchema,
  filename: z.string().min(1),
  mimeType: z.string().min(1),
  sizeBytes: z.number().int().min(0),
  durationMs: z.number().int().positive().max(PARTICIPANT_AUDIO_DURATION_MAX_MS).optional(),
  transcription: participantTranscriptionSchema.optional(),
})
export type ParticipantAttachment = z.infer<typeof participantAttachmentSchema>

/** Em unidades UTF-16, que é o que `.max` do zod conta. */
export const PARTICIPANT_ORIGINAL_TEXT_MAX_UTF16 = 20_000

export const participantMessageSchema = z.object({
  id: z.string().min(1),
  clientMessageId: z.string().min(1).optional(),
  direction: messageDirectionSchema,
  authorName: z.string().nullable().optional(),
  text: z.string().nullable().optional(),
  /**
   * A mensagem como chegou, antes de o host aparar (ex.: o e-mail inteiro, com o histórico citado).
   * Aparece recolhida dentro do balão; ausente ou igual a `text` não mostra nada.
   */
  originalText: z.string().max(PARTICIPANT_ORIGINAL_TEXT_MAX_UTF16).nullable().optional(),
  attachments: z.array(participantAttachmentSchema),
  createdAt: z.string().datetime(),
  status: messageDeliveryStatusSchema.optional(),
  readAt: z.string().datetime().nullable().optional(),
})
export type ParticipantMessage = z.infer<typeof participantMessageSchema>
