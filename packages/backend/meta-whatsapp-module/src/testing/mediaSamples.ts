/**
 * Devolve uma cópia nova a cada chamada: quem recebe pode escrever no buffer sem contaminar a
 * próxima leitura da mesma amostra.
 */
export function readMediaSample(name: MediaSampleName): Buffer {
  return Buffer.from(SAMPLE_BYTES[name], 'base64')
}

export function findMediaSample(name: MediaSampleName): MediaSample {
  const sample = MEDIA_SAMPLES.find((candidate) => candidate.name === name)
  if (!sample) throw new Error(`Amostra de mídia desconhecida: ${name}`)
  return sample
}
