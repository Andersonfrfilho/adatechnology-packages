/**
 * Amostras binárias mínimas, uma por tipo de mídia que a Meta aceita.
 *
 * Existem porque payload de mídia sem bytes não exercita nada de verdade: quem semeia uma
 * biblioteca de documentos ou testa ingestão precisa de arquivo que o leitor do sistema
 * operacional consiga ABRIR. Um `.txt` rotulado `application/pdf` passa por toda a pilha e só
 * falha na frente do usuário, que é o único lugar onde não dá para corrigir.
 *
 * Por isso cada amostra é um arquivo legítimo do seu formato — mínimo, porém válido: o PDF abre
 * com uma página em branco, o XLSX abre com uma planilha vazia, o OGG toca silêncio.
 *
 * Vêm embutidas em base64, e não como arquivos no pacote, porque asset solto obrigaria o consumidor
 * a resolver caminho dentro de `node_modules` — que muda com bundler, com ESM/CJS e com pnpm. São
 * ~9 KB no total; o custo de embutir é menor que o de resolver caminho.
 */

import type { InboundMediaType } from '@adatechnology/meta-whatsapp-contracts/testing'

/** Chave da amostra: o formato, não a extensão do arquivo. */
export type MediaSampleName =
  | 'pdf'
  | 'docx'
  | 'xlsx'
  | 'txt'
  | 'csv'
  | 'zip'
  | 'png'
  | 'jpeg'
  | 'webp'
  | 'mp4'
  | 'ogg'
  | 'm4a'
  | 'aac'
  | 'mp3'

export type MediaSample = {
  readonly name: MediaSampleName
  readonly mimeType: string
  /** Extensão sugerida para compor um nome de arquivo — sem o ponto. */
  readonly extension: string
  /**
   * Espécie com que a Meta entregaria essa mídia por padrão. É só o default: a mesma foto chega
   * como `image` quando enviada pela câmera e como `document` quando anexada pelo seletor de
   * arquivos, e o consumidor pode escolher a outra.
   */
  readonly mediaType: InboundMediaType
  readonly sizeBytes: number
}

